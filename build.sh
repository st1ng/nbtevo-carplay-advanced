#!/bin/zsh
# Builds the CarPlay Advanced Settings plugin (ARMv7, QNX, freestanding) into plugin/.
#
# Needs only clang and ld.lld. No firmware files: the plugin's imports (HMI frameworks, QNX libc) are resolved at run time inside the
# HMI / Connectivity / mm-ipod processes, so the link only needs the libraries' names. Empty stand-ins with those sonames are made in
# out/stubs and give the outputs the same DT_NEEDED entries as linking against the real libraries.
set -e
cd "$(dirname "$0")"
OUT=plugin
CF=(-target armv7-none-eabi -march=armv7-a -mfloat-abi=soft -ffreestanding -fPIC -Os -mno-unaligned-access -fno-exceptions -fno-rtti -nostdlib -Wno-everything)
LLD=${LLD:-$HOME/.rustup/toolchains/stable-aarch64-apple-darwin/lib/rustlib/aarch64-apple-darwin/bin/gcc-ld/ld.lld}
[ -x "$LLD" ] || LLD=$(command -v ld.lld) || { echo "ld.lld not found (set LLD=)"; exit 1; }
LD=($LLD -shared -z max-page-size=4096 -z common-page-size=4096 -z norelro -z noseparate-code --no-rosegment --hash-style=sysv --no-eh-frame-hdr -z nognustack --allow-shlib-undefined)
mkdir -p out/stubs $OUT

# "Enable knob tilts": the HMI patch words for each supported build
python3 -c '
import json, sys
for var, path in zip(sys.argv[1::2], sys.argv[2::2]):
    d = json.load(open(path))
    print("// generated by build.sh from %s (HMI %s)" % (path.split("/")[-1], d["hmi"]))
    print("const Word %s[] = {" % var)
    for w in d["words"]: print("  { %s, 0x%s, 0x%s }," % (w["addr"], w["orig"], w["new"]))
    print("};")
' kTilt006 src/tilt_006.json kTilt1703 src/tilt_1703.json > out/tilt.inc

# the plugin (loaded by the HMI)
clang "${CF[@]}" -I. -c src/cpm.cpp -o out/cpm.o

# soname stand-ins for QNX libc and the HMI's two frameworks. Two details make the outputs byte-identical to a link against the real
# libraries: the frameworks define _end/_edata/__bss_start/__exidx_* (lld then adds its own to libCarPlayMenu.so, in this order), and their bmw:: functions are typed
# as functions (the stand-in defines every bmw:: symbol cpm.cpp imports as an empty function).
printf '.data\n.globl __exidx_end, __bss_start, _end, _edata, __exidx_start\n__exidx_end: __bss_start: _end: _edata: __exidx_start: .word 0\n.text\n' > out/stubs/fw.s
for s in $(nm -u out/cpm.o | awk '{print $NF}' | grep '^_ZN3bmw'); do printf '.globl %s\n.type %s,%%function\n%s: bx lr\n' $s $s $s >> out/stubs/fw.s; done
clang "${CF[@]}" -c out/stubs/fw.s -o out/stubs/fw.o
echo > out/stubs/empty.c
clang "${CF[@]}" -x c -c out/stubs/empty.c -o out/stubs/empty.o
$LD -soname libc.so.3 -o out/stubs/libc.so.3 out/stubs/empty.o
$LD -soname libAppFramework.A.so -o out/stubs/libAppFramework.A.so out/stubs/fw.o
$LD -soname libCoreFramework.A.so -o out/stubs/libCoreFramework.A.so out/stubs/empty.o
LIBS=(-Lout/stubs -l:libc.so.3)

# link the plugin
$LD -soname libCarPlayMenu.so -o $OUT/libCarPlayMenu.so out/cpm.o -Lout/stubs -l:libAppFramework.A.so -l:libCoreFramework.A.so $LIBS
# the HUD-only menu (the turn-by-turn-only install, --hud): the same plugin with only the HUD rows, installed as libCarPlayMenu.so /
# CarPlayMenu.xml; its XML is the main one cut down to states 20 (two rows), 81 and 93
clang "${CF[@]}" -I. -DCPM_HUD_ONLY -c src/cpm.cpp -o out/cpm-hud.o
$LD -soname libCarPlayMenu.so -o $OUT/libCarPlayMenu-hud.so out/cpm-hud.o -Lout/stubs -l:libAppFramework.A.so -l:libCoreFramework.A.so $LIBS
python3 - $OUT/CarPlayMenu.xml $OUT/CarPlayMenu-hud.xml <<'HUDXML'
import re, sys
import xml.etree.ElementTree as ET
src, dst = sys.argv[1], sys.argv[2]
text = open(src).read()
app = ET.fromstring(text[text.index('<pluginApps'):]).find('pluginApp')
keep_states, keep_rows = {20, 81, 93}, {8, 80}          # state 20: "CarPlay directions in HUD" (action 8), "HUD effects >" (80)
states = app.find('hmiStates')
for st in list(states):
    if int(st.get('id')) not in keep_states:
        states.remove(st)
for c in list(states.find("hmiState[@id='20']").find('components')):
    if int(c.get('action')) not in keep_rows:
        states.find("hmiState[@id='20']").find('components').remove(c)
used = {int(app.find('entryButton').get('action')), int(app.find('entryButton').get('model'))}
for st in states:
    used.add(int(st.get('textModel')))
    for c in st.find('components'):
        used |= {int(c.get(k)) for k in ('action', 'model', 'textModel') if c.get(k)}
acts = app.find('actions')
for a in list(acts):
    if a.tag != 'combinedAction' and int(a.get('id')) not in used:
        acts.remove(a)
models = app.find('models')
for m in list(models):
    if int(m.get('id')) not in used:
        models.remove(m)
ET.indent(app, '  ')
head = ('<?xml version="1.0" encoding="UTF-8"?>\n<!-- CarPlay Advanced Settings, HUD-only menu (src/cpm.cpp built with CPM_HUD_ONLY), generated by build.sh '
        'from CarPlayMenu.xml.\n       20 CarPlay Advanced Settings: CarPlay directions in HUD, HUD effects >\n       81   HUD effects: Fill toward the turn, '
        'Blink near the turn, Effect colour >\n       93     Effect colour: Orange, Grey, White -->\n')
open(dst, 'w').write(head + '<pluginApps>\n  ' + ET.tostring(app, encoding='unicode').rstrip() + '\n</pluginApps>\n')
HUDXML
# touchpad / knob / pinch hook preloaded into Connectivity
clang "${CF[@]}" -x c -c src/pinch.c -o out/pinch.o
$LD -soname libcppinch.so -o $OUT/libcppinch.so out/pinch.o $LIBS
# "Restart to apply": reboots the head unit (LD_PRELOAD=... /bin/cat, see src/reboot.c)
clang "${CF[@]}" -x c -c src/reboot.c -o out/reboot.o
$LD -soname libcpreboot.so -o $OUT/libcpreboot.so out/reboot.o $LIBS
# installer probe: which cluster output the car has (Ethernet KOMBI or MOST); LD_PRELOAD=libcpprobe.so /bin/cat (see src/probe.cpp; also clears a left-over KOMBI arrow for librghook-kombi.so)
clang "${CF[@]}" -c src/probe.cpp -o out/probe.o
$LD -soname libcpprobe.so -o $OUT/libcpprobe.so out/probe.o $LIBS
# "Add route guidance to HUD": preloaded into mm-ipod
clang -target armv7-none-eabi -march=armv7-a -mfloat-abi=soft -ffreestanding -fPIC -Os -mno-unaligned-access \
      -Wno-incompatible-library-redeclaration -Wno-builtin-requires-header -c src/rghook.c -o out/rghook.o
$LD -soname librghook.so -o $OUT/librghook.so out/rghook.o $LIBS
# ... and its variants, one of which the installer puts in place of librghook.so (same soname: the mm-ipod wrapper preloads
# "librghook.so"): -kombi sends the guidance to an Ethernet KOMBI (src/rgkombi.cpp); -most draws it on the MOST HUDTerminal from
# mm-ipod (src/rghud.cpp, the plugin's hud.h), for installs without the menu plugin; -both does the two. The C++ parts each keep hidden
# copies of the EABI memcpy/memclr helpers: --allow-multiple-definition keeps one.
clang "${CF[@]}" -c src/rgkombi.cpp -o out/rgkombi.o
clang "${CF[@]}" -c src/rghud.cpp -o out/rghud.o
for v in kombi most both; do
  case $v in kombi) D=(-DRGHOOK_KOMBI); O=(out/rgkombi.o) ;; most) D=(-DRGHOOK_MOST); O=(out/rghud.o) ;;
              both) D=(-DRGHOOK_KOMBI -DRGHOOK_MOST); O=(out/rgkombi.o out/rghud.o) ;; esac
  clang -target armv7-none-eabi -march=armv7-a -mfloat-abi=soft -ffreestanding -fPIC -Os -mno-unaligned-access "${D[@]}" \
        -Wno-incompatible-library-redeclaration -Wno-builtin-requires-header -c src/rghook.c -o out/rghook-$v.o
  $LD --allow-multiple-definition -soname librghook.so -o $OUT/librghook-$v.so out/rghook-$v.o "${O[@]}" $LIBS
done
# menu texts
python3 src/texts.py $OUT/CarPlayMenu_ALL_Texts.zip
ls -l $OUT
