#!/usr/bin/env python3
"""Mapbox's maneuver drawings as HUD pieces: writes src/hudglyphs.h (and a JSON preview).

    curl -sL https://raw.githubusercontent.com/mapbox/mapbox-navigation-ios/v0.40.0/MapboxNavigation/ManeuversStyleKit.swift -o /tmp/msk.swift
    curl -sL https://raw.githubusercontent.com/mapbox/mapbox-navigation-ios/v0.40.0/MapboxNavigation/LanesStyleKit.swift -o /tmp/lsk.swift
    python3 tools/hud_glyphs.py /tmp/msk.swift /tmp/lsk.swift src/hudglyphs.h [preview.json]

Source: ManeuversStyleKit.swift and LanesStyleKit.swift of mapbox-navigation-ios v0.40.0 (ISC licence, see the header it writes), generated by PaintCode from
Mapbox's Maneuvers.pcvd (CC0, github.com/mapbox/navigation-ui-resources). tools/mapbox_stylekit.py interprets the drawing code.

The HUD terminal draws filled polygons only, so every drawing becomes convex pieces of at most 8 points: curves are flattened, filled
outlines are cut into triangles (ear clipping) and merged back into convex pieces (Hertel-Mehlhorn), strokes become one quad per segment
(overlapping a little so the joins close). Tone 0 = Mapbox's primary colour (the route), 1 = secondary (context). Coordinates: Mapbox's
32 x 32 canvas scaled into the 6WA box (70,20)-(170,120) that hudshapes.h uses; the roundabout's exit arrow stays in its own frame
(1/16 units) because the head unit turns it to the exit angle. The lane drawings stay in their own 30 x 30 frame (1/16 units, 0..480):
hudshapes.h scales each into its lane of the strip; they are flattened more coarsely (a lane is ~13 pixels wide on the HUD).
"""
import json
import math
import sys

sys.path.insert(0, __file__.rsplit('/', 1)[0])
import mapbox_stylekit as sk  # noqa: E402

BOX = 100 / 32.0              # Mapbox unit -> 6WA box unit
TOL = 0.08                    # curve flattening tolerance (Mapbox units)
EPS = 0.10                    # outline simplification (Mapbox units)


# ---- geometry ---------------------------------------------------------------------------------------------------------------------
def cubic(p0, c1, c2, p3, tol=TOL):
    length = math.dist(p0, c1) + math.dist(c1, c2) + math.dist(c2, p3)
    n = max(1, int(math.ceil(math.sqrt(length / tol) / 2)))
    out = []
    for i in range(1, n + 1):
        t = i / n; u = 1 - t
        out.append((u ** 3 * p0[0] + 3 * u * u * t * c1[0] + 3 * u * t * t * c2[0] + t ** 3 * p3[0],
                    u ** 3 * p0[1] + 3 * u * u * t * c1[1] + 3 * u * t * t * c2[1] + t ** 3 * p3[1]))
    return out


def flatten(sub):
    pts, closed, cur = [], False, None
    for seg in sub:
        if seg[0] == 'M': cur = seg[1]; pts.append(cur)
        elif seg[0] == 'L': cur = seg[1]; pts.append(cur)
        elif seg[0] == 'C': pts += cubic(cur, seg[1], seg[2], seg[3]); cur = seg[3]
        elif seg[0] == 'Z': closed = True
    clean = []
    for p in pts:
        if not clean or math.dist(p, clean[-1]) > 1e-3: clean.append(p)
    if closed and len(clean) > 2 and math.dist(clean[0], clean[-1]) < 1e-3: clean.pop()
    return clean, closed


def seg_dist(p, a, b):
    ax, ay = a; bx, by = b; px, py = p
    dx, dy = bx - ax, by - ay; L = dx * dx + dy * dy
    if L == 0: return math.dist(p, a)
    t = max(0, min(1, ((px - ax) * dx + (py - ay) * dy) / L))
    return math.dist(p, (ax + t * dx, ay + t * dy))


def dp(pts, eps):
    if len(pts) < 3: return pts
    i, d = max(((i, seg_dist(pts[i], pts[0], pts[-1])) for i in range(1, len(pts) - 1)), key=lambda x: x[1])
    if d <= eps: return [pts[0], pts[-1]]
    return dp(pts[:i + 1], eps)[:-1] + dp(pts[i:], eps)


def simplify_closed(pts, eps=EPS):
    if len(pts) <= 4: return pts
    far = max(range(len(pts)), key=lambda i: math.dist(pts[0], pts[i]))
    a = dp(pts[:far + 1], eps); b = dp(pts[far:] + [pts[0]], eps)
    out = a[:-1] + b[:-1]
    return out if len(out) >= 3 else pts


def area(pts):
    return sum(pts[i][0] * pts[(i + 1) % len(pts)][1] - pts[(i + 1) % len(pts)][0] * pts[i][1] for i in range(len(pts))) / 2


def cross(o, a, b):
    return (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0])


def inside_tri(p, a, b, c):
    return cross(a, b, p) >= -1e-9 and cross(b, c, p) >= -1e-9 and cross(c, a, p) >= -1e-9


def triangulate(pts):
    """ear clipping; pts counter-clockwise in a y-up sense (positive area); returns index triples"""
    idx = list(range(len(pts))); tris = []; guard = 0
    while len(idx) > 3 and guard < 10000:
        guard += 1; n = len(idx); found = False
        for k in range(n):
            i0, i1, i2 = idx[k - 1], idx[k], idx[(k + 1) % n]
            a, b, c = pts[i0], pts[i1], pts[i2]
            if cross(a, b, c) <= 1e-9: continue
            if any(inside_tri(pts[j], a, b, c) for j in idx if j not in (i0, i1, i2)): continue
            tris.append((i0, i1, i2)); idx.pop(k); found = True; break
        if not found:                                         # degenerate: drop the flattest vertex
            k = min(range(n), key=lambda k: abs(cross(pts[idx[k - 1]], pts[idx[k]], pts[idx[(k + 1) % n]]))); idx.pop(k)
    if len(idx) == 3 and cross(pts[idx[0]], pts[idx[1]], pts[idx[2]]) > 1e-9: tris.append(tuple(idx))
    return tris


def convex_poly(poly, pts):
    n = len(poly)
    for i in range(n):
        if cross(pts[poly[i - 1]], pts[poly[i]], pts[poly[(i + 1) % n]]) < -1e-9: return False
    return True


def merge_convex(tris, pts, maxk=8):
    polys = [list(t) for t in tris]
    changed = True
    while changed:
        changed = False
        for i in range(len(polys)):
            for j in range(i + 1, len(polys)):
                a, b = polys[i], polys[j]
                for x in range(len(a)):
                    u, v = a[x], a[(x + 1) % len(a)]
                    if v in b and b[(b.index(v) + 1) % len(b)] == u:            # shared edge u-v (b runs v -> u)
                        y = b.index(v)
                        merged = a[:x + 1] + [b[(y + k) % len(b)] for k in range(2, len(b))] + a[x + 1:]
                        if len(merged) <= maxk and convex_poly(merged, pts):
                            polys[i] = merged; polys.pop(j); changed = True
                        break
                if changed: break
            if changed: break
    return polys


def fill_pieces(outline):
    pts = simplify_closed(outline)
    if area(pts) < 0: pts = pts[::-1]
    tris = triangulate(pts)
    return [[pts[k] for k in poly] for poly in merge_convex(tris, pts)]


def stroke_pieces(pts, closed, width):
    out, h, ext = [], width / 2, width * 0.18
    segs = list(zip(pts, pts[1:] + ([pts[0]] if closed else [])))
    for k, (a, b) in enumerate(segs):
        L = math.dist(a, b)
        if L < 1e-6: continue
        ux, uy = (b[0] - a[0]) / L, (b[1] - a[1]) / L
        e0 = ext if (closed or k > 0) else 0; e1 = ext if (closed or k < len(segs) - 1) else 0
        a2 = (a[0] - ux * e0, a[1] - uy * e0); b2 = (b[0] + ux * e1, b[1] + uy * e1)
        nx, ny = -uy * h, ux * h
        out.append([(a2[0] + nx, a2[1] + ny), (b2[0] + nx, b2[1] + ny), (b2[0] - nx, b2[1] - ny), (a2[0] - nx, a2[1] - ny)])
    return out


def merge_stroke(pieces, pts):
    """consecutive stroke quads along a gentle curve stay separate (each convex); kept as is"""
    return pieces


def glyph(src_fns, name, params=None, tol=None):
    args, body = src_fns[name]
    pieces = []
    global TOL, EPS
    was = (TOL, EPS)
    if tol: TOL, EPS = tol
    for s in sk.run(body, params or {}):
        tone = 1 if s['color'] == 'secondary' else 0
        if s['kind'] == 'fill':
            subs = [flatten(sp)[0] for sp in s['subpaths']]
            if len(subs) == 2:                                                        # an outline with a hole (the pin): hole in tone 1
                outer, hole = sorted(subs, key=lambda q: -abs(area(q)))
                pieces += [(tone, p) for p in fill_pieces(outer)] + [(1, p) for p in fill_pieces(hole)]
            else:
                for sp in subs: pieces += [(tone, p) for p in fill_pieces(sp)]
        else:
            for sp in s['subpaths']:
                pts, closed = flatten(sp)
                pts = dp(pts, EPS / 2) if not closed else simplify_closed(pts, EPS / 2)
                pieces += [(tone, p) for p in stroke_pieces(pts, closed, s['width'])]
    TOL, EPS = was
    return pieces


# the lane drawings (LanesStyleKit), each a right-hand version (hudshapes.h mirrors them for the left). The "Only" ones are the
# straight + right lane with one way in the secondary colour: StraightOnly = go straight (the turn dim), RightOnly = turn (straight dim).
LANES = ['LaneStraight', 'LaneSlightRight', 'LaneRight', 'LaneUturn', 'LaneStraightRight', 'LaneStraightOnly', 'LaneRightOnly']
LANE_TOL = (1.2, 1.0)         # coarser: a lane is drawn ~13 x 17 pixels         # coarser: a lane is drawn ~13 x 17 pixels         # coarser: a lane is drawn ~13 x 17 pixels         # coarser: a lane is drawn ~13 x 17 pixels         # coarser: a lane is drawn ~13 x 17 pixels


STATIC = ['Arrowstraight', 'Arrowright', 'Arrowslightright', 'Arrowsharpright', 'Arrow180right', 'Arrive', 'Arriveright', 'Starting',
          'Destination', 'Merge', 'Fork', 'Offramp']


def roundabout_arrow(src_fns):
    """the exit arrow of drawRoundabout (bezier2Path) in its own frame, before the head unit turns it"""
    args, body = src_fns['Roundabout']
    start = body.index('let bezier2Path = UIBezierPath()'); end = body.index('bezier2Path.fill()')
    shapes = sk.run('\n'.join(body[start:end].split('\n') + ['primaryColor.setFill()', 'bezier2Path.fill()']))
    return [(0, p) for p in fill_pieces(flatten(shapes[0]['subpaths'][0])[0])]


def to_box(p):
    return (int(round(70 + p[0] * BOX)), int(round(20 + p[1] * BOX)))


